/**
 * Generates src/share/fileIconMap.ts from the Material Icon Theme manifest.
 *
 * The theme ships 1250 icons and maps 1378 extensions onto them. Bundling
 * all of it to label a transfer list would be absurd, and hand-writing the
 * mapping would be wrong within a month. So a curated set of icons is
 * chosen here, and every extension the real manifest points at one of them
 * is carried over verbatim: 68 icons, and the extensions come out right
 * because they are not guesses.
 *
 * Run after upgrading material-icon-theme:
 *   node scripts/build-file-icons.mjs
 */

import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const manifest = require("material-icon-theme/dist/material-icons.json");

/**
 * The icons worth shipping: the ones a person actually sends to somebody
 * across a room. Anything outside this set resolves to the generic file.
 */
const CURATED = [
  // Fallbacks and folders
  "file", "folder", "folder-open",
  // Code
  // "react_ts" is the one the theme gives .tsx; without it every .tsx
  // fell through to the generic file, which on a tool developers send
  // source to is the wrong file to get wrong.
  "javascript", "typescript", "react", "react_ts", "python", "go", "rust",
  "java", "c", "cpp", "csharp", "php", "ruby", "swift", "kotlin", "console",
  "html", "css", "sass", "json", "yaml", "xml", "markdown", "toml",
  "jupyter", "lua", "perl", "r", "dart", "scala", "haskell", "elixir",
  "vue", "svelte", "astro",
  // Documents and data
  "pdf", "word", "powerpoint", "table", "document", "database", "log",
  "epub",
  // Media
  "image", "svg", "video", "audio", "font",
  "adobe-photoshop", "adobe-illustrator", "figma",
  // Archives and binaries
  "zip", "exe", "disc", "hex", "android",
  // Config and tooling
  "settings", "tune", "git", "docker", "npm", "nodejs", "lock", "key",
  "certificate", "makefile", "cmake",
];

const wanted = new Set(CURATED);
const pick = (source) =>
  Object.fromEntries(
    Object.entries(source)
      .filter(([, icon]) => wanted.has(icon))
      .sort(([a], [b]) => a.localeCompare(b)),
  );

const extensions = pick(manifest.fileExtensions);
const names = pick(manifest.fileNames);

const ident = (icon) =>
  `svg${icon.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase())}`;

const lines = [
  "/*",
  " * Generated by scripts/build-file-icons.mjs. Do not edit by hand.",
  " *",
  " * Icons and mappings are from the Material Icon Theme (MIT), the same",
  ` * set VS Code shows. ${CURATED.length} icons covering ${Object.keys(extensions).length} extensions`,
  ` * and ${Object.keys(names).length} exact filenames.`,
  " */",
  "",
  ...CURATED.map(
    (icon) =>
      `import ${ident(icon)} from "material-icon-theme/icons/${icon}.svg?raw";`,
  ),
  "",
  "export const ICONS: Record<string, string> = {",
  ...CURATED.map((icon) => `  ${JSON.stringify(icon)}: ${ident(icon)},`),
  "};",
  "",
  "/** Lowercased extension to icon name. Longest suffix wins. */",
  "export const BY_EXTENSION: Record<string, string> = {",
  ...Object.entries(extensions).map(
    ([ext, icon]) => `  ${JSON.stringify(ext)}: ${JSON.stringify(icon)},`,
  ),
  "};",
  "",
  "/** Lowercased whole filename, checked before any extension. */",
  "export const BY_NAME: Record<string, string> = {",
  ...Object.entries(names).map(
    ([name, icon]) => `  ${JSON.stringify(name)}: ${JSON.stringify(icon)},`,
  ),
  "};",
  "",
];

const out = fileURLToPath(new URL("../src/share/fileIconMap.ts", import.meta.url));
writeFileSync(out, lines.join("\n"));

console.log(
  `wrote fileIconMap.ts: ${CURATED.length} icons, ` +
    `${Object.keys(extensions).length} extensions, ${Object.keys(names).length} filenames`,
);
